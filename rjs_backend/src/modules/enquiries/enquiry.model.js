import mongoose from 'mongoose';
const enquirySchema=new mongoose.Schema({
    enquiryNumber:{
        type:String,
        unique:true,
        index:true
    },
    customer:{
        name:{
            type:String,
            required:true,
            trim:true
        },
        phone:{
            type:String,
            required:true,
            trim:true
        },
        email:{
            type:String,
            trim:true
        }
    },
    locations:{
        type:[
            {
                address:{
                    type:String,
                    required:true,
                    trim:true
                },
                order:{
                    type:Number,
                    required:true
                }
            }
        ],
        validate:{
            validator:(value)=>value.length>=2,
            message:'At least pickup and drop locations are required'
        }
    },
    startDate:{
        type:Date,
        required:true
    },
    numberOfDays:{
        type:Number,
        min:1,
        max:365,
        required:true
    },
    passengerCount:{
        type:Number,
        min:1,
        max:100,
        required:true
    },
    categoryId:{
        type:mongoose.Schema.Types.ObjectId,
        ref:'VehicleCategory',
        required:true
    },
    variantId:{
        type:mongoose.Schema.Types.ObjectId,
        ref:'VehicleVariant',
        required:true
    },
    estimatedDistanceKm:{
        type:Number,
        min:0
    },
    pricing:{
        ratePerKm:{
            type:Number,
            min:0,
            default:0
        },
        dailyCharge:{
            type:Number,
            min:0,
            default:0
        },
        extraCharges:{
            type:Number,
            min:0,
            default:0
        }
    },
    estimatedPrice:{
        type:Number,
        min:0,
        required:true
    },
    notes:{
        type:String,
        trim:true,
        maxLength:2000
    },
    status:{
        type:String,
        enum:['DRAFT','QUOTED','CONFIRMED','CANCELLED'],
        default:'QUOTED',
        index:true
    },
    createdBy:{
        type:mongoose.Schema.Types.ObjectId,
        ref:'AdminAccount',
        required:true
    },
    bookingId:{
        type:mongoose.Schema.Types.ObjectId,
        ref:'Booking'
    },
},{timestamps:true});

enquirySchema.pre('validate',function(){
    if(!this.enquiryNumber)this.enquiryNumber='ENQ'+Date.now().toString().slice(-8);
});

const Enquiry=mongoose.model('Enquiry',enquirySchema);
export{Enquiry};
